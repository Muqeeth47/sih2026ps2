/**
 * Validates whether an extracted sub-caste is notified under Article 342 for the given State
 */
export function validateSubCasteAgainstOrder(
  state: string,
  subCaste: string
): { isValid: boolean; matchedEntry?: string; legalCitation: string } {
  const normalizedState =
    Object.keys(CENTRAL_ST_ORDER_DATASET).find(
      (k) => k.toLowerCase() === state.trim().toLowerCase()
    ) || 'Rajasthan';

  const tribes = CENTRAL_ST_ORDER_DATASET[normalizedState] || [];
  const normalizedCaste = subCaste.trim().toLowerCase();

  const matched = tribes.find(
    (t) =>
      t.toLowerCase() === normalizedCaste ||
      t.toLowerCase().includes(normalizedCaste) ||
      normalizedCaste.includes(t.toLowerCase())
  );

  if (matched) {
    return {
      isValid: true,
      matchedEntry: matched,
      legalCitation: `Notified under Constitution (Scheduled Tribes) Order, 1950 for ${normalizedState} (Schedule 1). Valid ST Status.`,
    };
  }

  return {
    isValid: false,
    legalCitation: `UNVERIFIED CLAIM: Sub-caste "${subCaste}" is NOT notified under Central Presidential ST Order for ${state}. Possible general/OBC/invalid filing.`,
  };
}
